async function main() {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet('업데이트');
  const headers = ['No.', '화면', '화면', '화면', '화면', '기능', '사전 조건', '절차', '예상결과', '기획서', 'QA 확인 결과', 'JIRA', '비고'];
  const sub = ['', '(0 depth)', '(1 depth)', '(2 depth)', '(3 depth)', '', '', '', '', '', '', '', ''];
  ws.addRow(headers); ws.addRow(sub);
  ws.mergeCells('B1:E1');
  ['A', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M'].forEach(c => ws.mergeCells(`${c}1:${c}2`));
  R.forEach((r, i) => ws.addRow([i + 1, S0, S1, r[0], r[1], r[2], r[3], r[4], r[5], r[6], '', '', r[7]]));
  const first = 3, last = first + R.length - 1;
  ws.mergeCells(`B${first}:B${last}`); ws.mergeCells(`C${first}:C${last}`);
  let gs = first;
  for (let i = 1; i <= R.length; i++) {
    const cur = R[i - 1][0], nxt = i < R.length ? R[i][0] : null;
    if (cur !== nxt) { const rs = gs, re = first + i - 1; if (re > rs) ws.mergeCells(`D${rs}:D${re}`); gs = first + i; }
  }
  const widths = [5, 14, 10, 14, 20, 8, 22, 30, 46, 24, 12, 8, 30];
  widths.forEach((w, i) => (ws.getColumn(i + 1).width = w));
  ws.eachRow((row, rn) => {
    row.eachCell(cell => { cell.alignment = { vertical: 'top', wrapText: true }; cell.border = { top: { style: 'thin', color: { argb: 'FFDDDDDD' } }, bottom: { style: 'thin', color: { argb: 'FFDDDDDD' } }, left: { style: 'thin', color: { argb: 'FFDDDDDD' } }, right: { style: 'thin', color: { argb: 'FFDDDDDD' } } }; });
    if (rn <= 2) row.eachCell(cell => { cell.font = { bold: true, color: { argb: 'FFFFFFFF' } }; cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1C1E54' } }; cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true }; });
  });
  ws.autoFilter = { from: { row: 2, column: 1 }, to: { row: last, column: headers.length } };
  ws.views = [{ state: 'frozen', ySplit: 2 }];
  const out = path.join(process.cwd(), 'tc', '업데이트_TC_2026-10_v1.xlsx');
  await wb.xlsx.writeFile(out);
  console.log('생성 완료:', out, '| 데이터 행:', R.length);
}
